const ALL_FLOWS: FlowDef[] = [...HUB_FLOWS, ...TRUNK_FLOWS, ...ABNORMAL_FLOWS]

function pick<T>(arr: readonly T[], i: number): T {
  return arr[i % arr.length]
}

/**
 * 生成全国物流轨迹演示数据。
 * 同一起讫组合只保留一条；货物/承运商/ETA 按索引轮转，保证视觉丰富但不重复堆叠。
 */
export function buildDemoTrackRoutes(): TrackRoute[] {
  return ALL_FLOWS.map((flow, i) => {
    const [originName, destName, abnormal] = flow
    const originCoord = CITY[originName]
    const destCoord = CITY[destName]
    return {
      taskNo: `WL-DEMO-${String(i + 1).padStart(3, "0")}`,
      carrier: pick(CARRIERS, i),
      driver: undefined,
      originName,
      destName,
      originCoord,
      destCoord,
      statusLabel: "运输中",
      trackStatusLabel: abnormal ? "轨迹偏离" : "轨迹正常",
      abnormal: Boolean(abnormal),
      goodsSummary: pick(GOODS, i),
      eta: `今日 ${18 + (i % 5)}:${["00", "15", "30", "45"][i % 4]}`,
    }
  })
}
